"""Minimal structural interface consumed by stateful orchestration."""
from typing import Protocol, Any
from mirage.contracts.capabilities import Evidence, OperandDescriptor


class Backend(Protocol):
    name: str

    def is_tensor(self, value: Any) -> bool: ...
    def describe_tensor(self, value: Any, path: tuple, object_group: int,
                        storage_group: int | None) -> OperandDescriptor: ...
    def storage_identity(self, value: Any) -> Any: ...
    def capability(self, name: str) -> Evidence: ...
    def mutation_actions(self, descriptor: OperandDescriptor) -> tuple[str, ...]: ...
    def mutation_eligibility(self, value: Any, action: str, obligations: Any) -> Evidence: ...
    def mutate(self, value: Any, action: str, obligations: Any) -> Any: ...
    def verify_mutation(self, source: Any, result: Any, action: str, obligations: Any) -> Evidence: ...
    def compare(self, left: Any, right: Any, policy: str) -> dict: ...
    def training_capabilities(self, context: dict, *, checkpoint: str,
                              provenance: dict, observed: dict | None = None) -> Any: ...


def require_capability(backend: Backend, name: str) -> Evidence:
    evidence = backend.capability(name)
    if not isinstance(evidence, Evidence):
        raise TypeError("Backend returned an untyped capability")
    return evidence
